# Generates font8x16.h: 8x16 1-bit glyphs for ASCII 32..126 plus Spanish letters (Latin-1), rendered from Consolas Bold.
from PIL import Image, ImageDraw, ImageFont
f = ImageFont.truetype('C:/Windows/Fonts/consolab.ttf', 14)
chars = [chr(c) for c in range(32, 127)] + list('áéíóúñÁÉÍÓÚÑ¿¡üÜ')
extra = ''.join('\\x%02x' % ord(c) for c in chars[95:])
out = ['/* generated by mkfont.py - 8x16 bitmap font; glyphs 95.. are the Latin-1 chars in font_extra */',
       'static const char font_extra[] = "%s";' % extra,
       'static const unsigned char font8x16[%d][16] = {' % len(chars)]
for ch in chars:
    im = Image.new('1', (8, 16), 0)
    ImageDraw.Draw(im).text((0, 0), ch, font=f, fill=1)
    rows = []
    for y in range(16):
        b = 0
        for x in range(8):
            if im.getpixel((x, y)):
                b |= 0x80 >> x
        rows.append('0x%02x' % b)
    out.append('\t{' + ','.join(rows) + '},')
out.append('};')
open('font8x16.h', 'w').write('\n'.join(out) + '\n')
print(len(chars), 'glyphs')
